// Generates one copy file per web component in copy/: a single ES module
// with every dependency inlined, for pasting into a project without the
// package. Reads the elements from the Custom Elements Manifest, so run it
// after `cem analyze`; CI fails if the output drifts.
import { readFileSync } from "node:fs"

import { build } from "tsdown"

import { customElements, type Manifest } from "./manifest.ts"

const OUT = "copy"

const manifest: Manifest = JSON.parse(
  readFileSync("dist/custom-elements.json", "utf8")
)
const pkg = JSON.parse(readFileSync("package.json", "utf8"))

const elements = customElements(manifest)
  .filter(({ declaration }) => declaration.tagName)
  .map(({ declaration, module }) => ({
    tag: declaration.tagName!,
    source: module.path,
  }))

for (const [index, { tag, source }] of elements.entries()) {
  // One build per element, so nothing is split into a shared chunk.
  await build({
    config: false,
    entry: { [tag]: source },
    outDir: OUT,
    clean: index === 0,
    format: ["esm"],
    dts: false,
    sourcemap: false,
    target: "es2022",
    platform: "browser",
    treeshake: true,
    logLevel: "warn",
    banner: { js: banner(tag) },
  })
}

function banner(tag: string): string {
  return [
    `/*! <${tag}> from ${pkg.name}, ${pkg.homepage.replace(/#.*$/, "")}`,
    ` * ${pkg.license} License, ${pkg.author}`,
    " *",
    " * Copy file: the whole web component in one module, with nothing to",
    " * install. Load it with <script type=\"module\" src=\"…\"></script>.",
    " * Generated by `pnpm build` from src/; do not edit it in the repo.",
    " */",
  ].join("\n")
}
